"""SQLite schema, and Postgres when Railway sets DATABASE_URL."""

from __future__ import annotations

import os
import sqlite3
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS farmers (
    phone TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    language TEXT NOT NULL,
    district TEXT,
    village TEXT,
    lat REAL,
    lon REAL,
    opt_in INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sowings (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    phone TEXT NOT NULL,
    crop TEXT NOT NULL,
    sow_date TEXT NOT NULL,
    quantity_qtl REAL,
    in_transit INTEGER NOT NULL DEFAULT 0,
    harvested INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS calls (
    id TEXT PRIMARY KEY,
    phone TEXT,
    direction TEXT NOT NULL,
    started_at TEXT NOT NULL,
    ended_at TEXT,
    language TEXT,
    summary TEXT,
    transcript TEXT,
    sms_body TEXT
);

CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    phone TEXT,
    language TEXT NOT NULL,
    created_at TEXT NOT NULL,
    status TEXT NOT NULL,
    context_json TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS prices (
    crop TEXT NOT NULL,
    role TEXT NOT NULL,
    market TEXT NOT NULL,
    district TEXT NOT NULL,
    date TEXT NOT NULL,
    arrival_tonnes REAL,
    min_price REAL,
    max_price REAL,
    modal_price REAL,
    PRIMARY KEY (crop, role, date)
);

CREATE TABLE IF NOT EXISTS triggers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    phone TEXT NOT NULL,
    crop TEXT NOT NULL,
    mandi TEXT NOT NULL,
    reason TEXT NOT NULL,
    citations TEXT NOT NULL,
    status TEXT NOT NULL,
    suppress_reason TEXT,
    created_at TEXT NOT NULL,
    result TEXT
);

CREATE TABLE IF NOT EXISTS gate_prices (
    crop TEXT PRIMARY KEY,
    modal REAL NOT NULL,
    min_price REAL,
    max_price REAL,
    entered_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS findings (
    kind TEXT NOT NULL,
    item_key TEXT NOT NULL,
    payload TEXT NOT NULL,
    source TEXT NOT NULL,
    retrieved_at TEXT NOT NULL,
    PRIMARY KEY (kind, item_key)
);

CREATE TABLE IF NOT EXISTS agent_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    plan_id TEXT NOT NULL,
    agent TEXT NOT NULL,
    claim TEXT NOT NULL,
    citation TEXT NOT NULL,
    created_at TEXT NOT NULL
);
"""


def _migrate(connection: sqlite3.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS findings (
            kind TEXT NOT NULL,
            item_key TEXT NOT NULL,
            payload TEXT NOT NULL,
            source TEXT NOT NULL,
            retrieved_at TEXT NOT NULL,
            PRIMARY KEY (kind, item_key)
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE IF NOT EXISTS gate_prices (
            crop TEXT PRIMARY KEY,
            modal REAL NOT NULL,
            min_price REAL,
            max_price REAL,
            entered_at TEXT NOT NULL
        )
        """
    )
    columns = {row[1] for row in connection.execute("PRAGMA table_info(sowings)")}
    if columns and "harvested" not in columns:
        connection.execute("ALTER TABLE sowings ADD COLUMN harvested INTEGER NOT NULL DEFAULT 0")
    if columns:
        connection.execute("UPDATE sowings SET harvested = 1 WHERE in_transit = 1 AND harvested = 0")
    connection.commit()


def connect(path: Path | str) -> sqlite3.Connection:
    # FastAPI resolves a dependency and then runs the handler on another worker thread.
    connection = sqlite3.connect(path, check_same_thread=False, timeout=30)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    _migrate(connection)
    return connection


def init_db(path: Path | str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with connect(path) as connection:
        connection.executescript(SCHEMA)


def rows(connection, query: str, params: tuple = ()) -> list[dict]:
    return [dict(row) for row in connection.execute(query, params).fetchall()]


def database_url() -> str:
    return os.environ.get("DATABASE_URL", "").strip()


PG_SCHEMA = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


class _PgResult:
    def __init__(self, rows_found: list[dict]):
        self._rows = rows_found

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return self._rows


class PgConnection:
    """The small slice of sqlite3.Connection this app uses."""

    dialect = "postgres"

    def __init__(self, connection):
        self._connection = connection

    def execute(self, query: str, params: tuple = ()):
        sql = query.replace("?", "%s").replace("datetime('now')", "CURRENT_TIMESTAMP")
        cursor = self._connection.execute(sql, params)
        found = cursor.fetchall() if cursor.description else []
        return _PgResult([dict(row) for row in found])

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)
        self.commit()

    def commit(self) -> None:
        self._connection.commit()

    def close(self) -> None:
        self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, *_args):
        self.close()
        return False


def postgres() -> PgConnection:
    import psycopg
    from psycopg.rows import dict_row

    raw = psycopg.connect(database_url(), row_factory=dict_row)
    # KisanCall already owns public.farmers and public.calls in this database.
    raw.execute("CREATE SCHEMA IF NOT EXISTS desk")
    raw.execute("SET search_path TO desk")
    raw.commit()
    connection = PgConnection(raw)
    connection.executescript(PG_SCHEMA)
    return connection


def open_store(path: Path | str):
    """Caller records live in Postgres on Railway, and in SQLite locally."""
    if database_url():
        return postgres()
    return connect(path)
